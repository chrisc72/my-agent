def lookup_tw_regulation(
    inci_name: str = "",
    cas_number: str = "",
    disabled_tables: list | None = None,
) -> list[dict]:
    """
    搜尋台灣法規資料庫。
    可用 INCI 名稱（部分符合）或 CAS Number（完整符合）搜尋。
    disabled_tables: 要排除的表格名稱清單（例如 ["成分使用限制"]）。
    回傳符合的所有法規條目清單。
    """
    results = []
    seen_ids = set()

    if not isinstance(inci_name, str):
        inci_name = ""
    if not isinstance(cas_number, str):
        cas_number = ""
    search_inci = inci_name.lower().strip() if inci_name else ""
    search_cas = cas_number.strip().replace(" ", "") if cas_number else ""

    active_regs = (
        [r for r in TW_REGULATIONS if r["table"] not in disabled_tables]
        if disabled_tables
        else TW_REGULATIONS
    )

    for i, entry in enumerate(active_regs):
        matched = False
        if search_inci:
            for name in entry["inci_names"]:
                if search_inci in name.lower():
                    matched = True
                    break
        if not matched and search_cas:
            for cas in entry["cas_numbers"]:
                if search_cas == cas.strip():
                    matched = True
                    break
        if matched and i not in seen_ids:
            results.append(entry)
            seen_ids.add(i)

    return results


def format_tw_result(entries: list[dict]) -> str:
    """將台灣法規搜尋結果格式化為易讀字串"""
    if not entries:
        return "未在台灣衛福部法規表中找到相關規定"

    lines = []
    for entry in entries:
        lines.append(f"【{entry['table']}表】")
        lines.append(f"INCI: {', '.join(entry['inci_names'][:3])}")
        if entry['cas_numbers']:
            lines.append(f"CAS: {', '.join(entry['cas_numbers'][:3])}")
        lines.append(f"限量標準: {entry['limit']}")
        if entry['product_type']:
            lines.append(f"適用範圍: {entry['product_type']}")
        if entry['warnings']:
            lines.append(f"注意事項: {entry['warnings']}")
        lines.append(f"來源: {entry['source']}")
        lines.append("")

    return "\n".join(lines)


